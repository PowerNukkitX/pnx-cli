const LANGS = Object.keys(DICT).filter((k) => k !== 'langName');

window.i18n = (() => {
    let lang = 'fr';

    function detect() {
        const nav = (navigator.language || 'fr').slice(0, 2).toLowerCase();
        return LANGS.includes(nav) ? nav : 'fr';
    }

    const t = (key) => {
        // the user's language, then English, then the project's French
        const hit = DICT[lang]?.[key] ?? DICT.en?.[key] ?? DICT.fr[key] ?? key;
        return typeof hit === 'string' ? hit : key;
    };

    function applyDom(root = document) {
        root.querySelectorAll('[data-i18n]').forEach((el) => {
            el.textContent = t(el.dataset.i18n);
        });
        root.querySelectorAll('[data-i18n-title]').forEach((el) => {
            el.setAttribute('title', t(el.dataset.i18nTitle));
        });
        root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
            el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
        });
    }

    function set(next) {
        if (!LANGS.includes(next)) return;
        lang = next;
        document.documentElement.lang = next;
        applyDom();
        document.dispatchEvent(new CustomEvent('i18n:change', { detail: lang }));
    }

    /** later scripts (i18n-ui.js) add or override keys, language by language */
    function extend(more) {
        for (const [code, entries] of Object.entries(more || {})) {
            if (!DICT[code]) continue;
            Object.assign(DICT[code], entries);
        }
    }

    return {
        t,
        extend,
        get: () => lang,
        langs: () => LANGS.map((code) => ({ code: code, name: DICT[code].langName })),
        detect,
        set,
        applyDom,
    };
})();
